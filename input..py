# SOLVING QUADRATIC EQUATION
# IP: a=1
# b=-3
# c=2
# OP: x1=2.0 , x2=1.0

a= int(input("enter a:"))
b= int(input("enter b:"))
c= int(input("enter c:"))
d= (b**2)-4*a*c
root1= (-b+(d**(0.5)))/(2*a)
root2= (-b-(d**(0.5)))/(2*a)
print(f"roots:({root1},{root2})")


